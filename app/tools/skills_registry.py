def get_skill_catalog():
    """返回所有已安装的技能列表（默认只有工具类）。"""
    return list(SKILL_CATALOG)


def get_all_skills():
    """返回技能市场所有技能（含未安装的）。"""
    return {
        "installed": list(SKILL_CATALOG),
        "market": PROMPT_SKILLS,
    }


def get_prompt_skill(skill_id: str) -> Optional[Dict[str, Any]]:
    """根据 id 获取提示词技能。"""
    for skill in PROMPT_SKILLS:
        if skill["id"] == skill_id:
            return skill
    return None


def get_prompt_skill_system_prompt(skill_id: str) -> Optional[str]:
    """获取提示词技能的系统提示词。"""
    skill = get_prompt_skill(skill_id)
    return skill.get("systemPrompt") if skill else None


def resolve_tools(enabled_skill_ids: List[str]):
    """根据前端选中的技能 id 解析 LangChain 工具列表。"""
    tools = []
    seen = set()
    for skill_id in enabled_skill_ids:
        for tool in SKILL_TOOLS.get(skill_id, []):
            tool_name = getattr(tool, "name", None) or str(tool)
            if tool_name not in seen:
                seen.add(tool_name)
                tools.append(tool)
    return tools
